-- depends on ./beneficiaries.sql and ./products.sql

CREATE TABLE client_sessions (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    BENEFICIARY_ID INT NOT NULL,
    DETAILS VARCHAR(255) NOT NULL,
    CONSTRAINT FK_CS_B FOREIGN KEY (BENEFICIARY_ID) REFERENCES beneficiaries (id) 
);

CREATE TABLE client_session_request (
    CS_ID INT NOT NULL,
    PRODUCT_ID INT NOT NULL,
    QUANTITY INT DEFAULT 1,
    CONSTRAINT PK_CSR PRIMARY KEY (CS_ID, PRODUCT_ID),
    CONSTRAINT FK_CSR_CS FOREIGN KEY (CS_ID) REFERENCES client_sessions (id),
    CONSTRAINT FK_CSR_P FOREIGN KEY (PRODUCT_ID) REFERENCES products (id)
);