-- depends on ./1.auth.sql, ./beneficiaries.sql, and ./products.sql

CREATE TABLE client_attendances (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    BENEFICIARY_ID INT NOT NULL,
    DETAILS VARCHAR(255) NOT NULL,
    CANCELLED_AT TIMESTAMP,
    CANCELLED_BY INT,
    CANCELLATION_REASON VARCHAR(256),
    CONSTRAINT FK_CA_B FOREIGN KEY (BENEFICIARY_ID) REFERENCES beneficiaries (id),
    CONSTRAINT FK_CA_U FOREIGN KEY (CANCELLED_BY) REFERENCES users (id)
);

CREATE TABLE client_attendance_request (
    ATTENDANCE_ID INT NOT NULL,
    PRODUCT_ID INT NOT NULL,
    QUANTITY INT DEFAULT 1,
    CONSTRAINT PK_CAR PRIMARY KEY (ATTENDANCE_ID, PRODUCT_ID),
    CONSTRAINT FK_CAR_ATTENDANCE FOREIGN KEY (ATTENDANCE_ID) REFERENCES client_attendances (id),
    CONSTRAINT FK_CAR_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES products (id)
);
