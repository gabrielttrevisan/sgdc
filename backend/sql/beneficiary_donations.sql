-- Depends on beneficiaries.sql, families.sql, 1.auth.sql,
-- in_stock_products.sql, sala.sql, and client_attendances.sql

CREATE TABLE donations (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    BENEFICIARY_ID INT NOT NULL,
    FAMILY_ID INT NOT NULL,
    REPRESENTATIVE_ID INT NOT NULL,
    ATTENDANCE_ID INT,
    DETAILS VARCHAR(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY INT NOT NULL,
    CANCELLED_AT TIMESTAMP,
    CANCELLED_BY INT,
    CONSTRAINT FK_DON_BEN FOREIGN KEY (BENEFICIARY_ID) 
        REFERENCES beneficiaries(id),
    CONSTRAINT FK_DON_FAM FOREIGN KEY (FAMILY_ID) 
        REFERENCES families(id),
    CONSTRAINT FK_DON_REP FOREIGN KEY (REPRESENTATIVE_ID)
        REFERENCES beneficiaries(id),
    CONSTRAINT FK_DON_ATT FOREIGN KEY (ATTENDANCE_ID) 
        REFERENCES client_attendances(id),
    CONSTRAINT FK_DON_OWNER FOREIGN KEY (CREATED_BY)
        REFERENCES users(id),
    CONSTRAINT FK_DON_CANCEL FOREIGN KEY (CANCELLED_BY)
        REFERENCES users(id)
);

CREATE TABLE donation_items (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DONATION_ID INT NOT NULL,
    PRODUCT_ID INT NOT NULL,
    ISP_ID INT NOT NULL,
    QUANTITY INT DEFAULT 1,
    ROOM_ID INT,
    CONSTRAINT FK_DI_DON FOREIGN KEY (DONATION_ID)
        REFERENCES donations (id),
    CONSTRAINT FK_DI_PRODUCT FOREIGN KEY (PRODUCT_ID)
        REFERENCES products (id),
    CONSTRAINT FK_DI_ISP FOREIGN KEY (ISP_ID)
        REFERENCES in_stock_products (id),
    CONSTRAINT FK_DI_ROOM FOREIGN KEY (ROOM_ID)
        REFERENCES salas (id)
);