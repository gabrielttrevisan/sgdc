-- dependes on arrecadacoes.sql, measuring_units.sql and 1.auth.sql

CREATE TABLE goals (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(128),
    DESCRIPTION VARCHAR(128),
    START_AT DATE,
    END_AT DATE,
    GOAL INT NOT NULL,
    IS_GLOBAL TINYINT DEFAULT 1,
    UNIT_ID INT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY INT NOT NULL,
    CONSTRAINT FK_GOALS_UNITS FOREIGN KEY (UNIT_ID)
        REFERENCES MEASURING_UNITS (ID),
    CONSTRAINT FK_GOALS_USERS FOREIGN KEY (CREATED_BY)
        REFERENCES USERS (ID)
);

CREATE TABLE goal_registries (
    GOAL_ID INT NOT NULL,
    ITEM_DRIVE_ID INT NOT NULL,
    PRIMARY KEY (GOAL_ID, ITEM_DRIVE_ID),
    CONSTRAINT FK_GR_GOALS FOREIGN KEY (GOAL_ID)
        REFERENCES GOALS (ID),
    CONSTRAINT FK_GR_ID FOREIGN KEY (ITEM_DRIVE_ID)
        REFERENCES ARRECADACOES (ID)
);
