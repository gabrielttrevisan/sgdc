CREATE TABLE in_stock_products (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    PRODUCT_ID INT NOT NULL,
    COUNT INT DEFAULT 1,
    EXPIRES_AT TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_ISP_PRODUCTS FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID)
);

CREATE TABLE isp_in_room (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ISP_ID INT NOT NULL,
    ROOM_ID INT NOT NULL,
    STORED_COUNT INT DEFAULT 1,
    CONSTRAINT FK_ISPIR_ROOMS FOREIGN KEY (ROOM_ID) REFERENCES SALAS(ID),
    CONSTRAINT FK_ISPIR_ISP FOREIGN KEY (ISP_ID) REFERENCES IN_STOCK_PRODUCTS(ID)
);