CREATE TABLE collections (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    COLLECTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    COLLECTED_BY INT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY INT NOT NULL,
    CONSTRAINT FK_DONATIONS_DONORS FOREIGN KEY (COLLECTED_BY) REFERENCES DONORS(ID),
    CONSTRAINT FK_DONATIONS_USERS FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID)
);

CREATE TABLE collected_items (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    PRODUCT_ID INT NOT NULL,
    COLLECTION_ID INT NOT NULL,
    COUNT INT DEFAULT 1,
    EXPIRES_AT TIMESTAMP,
    SALA_ID INT NOT NULL,
    CONSTRAINT FK_CI_SALAS FOREIGN KEY (SALA_ID) REFERENCES SALAS(ID),
    CONSTRAINT FK_DI_PRODUCTS FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID),
    CONSTRAINT FK_DI_DONATIONS FOREIGN KEY (COLLECTION_ID) REFERENCES COLLECTIONS(ID)
);