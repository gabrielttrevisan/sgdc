CREATE TABLE IF NOT EXISTS COLLECTIONS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    COLLECTED_BY INT NOT NULL,
    CREATED_BY INT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_COLLECTIONS_DONOR
        FOREIGN KEY (COLLECTED_BY) REFERENCES DONORS(ID),
    CONSTRAINT FK_COLLECTIONS_USER
        FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID)
);

CREATE TABLE IF NOT EXISTS COLLECTED_ITEMS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    PRODUCT_ID INT NOT NULL,
    COLLECTION_ID INT NOT NULL,
    `COUNT` INT NOT NULL,
    SALA_ID INT NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_COLLECTED_ITEMS_PRODUCT
        FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID),
    CONSTRAINT FK_COLLECTED_ITEMS_COLLECTION
        FOREIGN KEY (COLLECTION_ID) REFERENCES COLLECTIONS(ID),
    CONSTRAINT FK_COLLECTED_ITEMS_SALA
        FOREIGN KEY (SALA_ID) REFERENCES SALAS(ID)
);
