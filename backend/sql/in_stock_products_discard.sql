CREATE TABLE isp_discards (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY INT NOT NULL,
    DETAILS VARCHAR(256) NOT NULL,
    ALLOCATION_ID INT,
    CONSTRAINT FK_ISPD_A FOREIGN KEY (ALLOCATION_ID) REFERENCES ALLOCATIONS(ID),
    CONSTRAINT FK_ISPD_U FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID)
);

CREATE TABLE ispd_products (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DISCARD_ID INT NOT NULL,
    IN_STOCK_PRODUCT_ID INT NOT NULL,
    QUANTITY INT DEFAULT 1,
    DETAILS VARCHAR(128),
    CONSTRAINT FK_ISPDP_ISPD FOREIGN KEY (DISCARD_ID) REFERENCES ISP_DISCARDS(ID),
    CONSTRAINT FK_ISPDP_PROD FOREIGN KEY (IN_STOCK_PRODUCT_ID) REFERENCES isp_in_room(ID)
);

CREATE TABLE discard_volunteers (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DISCARD_ID INT NOT NULL,
    VOLUNTEER_ID INT NOT NULL,
    DETAILS VARCHAR(128),
    CONSTRAINT FK_DV_ISPD FOREIGN KEY (DISCARD_ID) REFERENCES ISP_DISCARDS(ID),
    CONSTRAINT FK_DV_VOL FOREIGN KEY (VOLUNTEER_ID) REFERENCES VOLUNTEERS(ID)
);