CREATE TABLE allocations (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    VOLUNTEER_ID INT NOT NULL,
    ALLOCATION_TYPE_ID INT NOT NULL,
    START_AT DATETIME NOT NULL,
    END_AT DATETIME NOT NULL,
    NOTES VARCHAR(255) NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP() ON UPDATE CURRENT_TIMESTAMP(),
    DELETED_AT TIMESTAMP NULL DEFAULT NULL,
    CONSTRAINT FK_ALLOCATIONS_VOLUNTEER FOREIGN KEY (VOLUNTEER_ID) REFERENCES volunteers (id),
    CONSTRAINT FK_ALLOCATIONS_ALLOCATION_TYPE FOREIGN KEY (ALLOCATION_TYPE_ID) REFERENCES allocation_types (ID)
);
